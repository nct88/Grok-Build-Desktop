  let lang = "en";

  function t(key) {
    const table = STR[lang] || STR.en;
    return table[key] ?? STR.en[key] ?? key;
  }

  function getLang() {
    return lang;
  }

  function setLang(next) {
    lang = next === "vi" ? "vi" : "en";
    try {
      localStorage.setItem("grok-build-lang", lang);
    } catch {
      // ignore
    }
    document.documentElement.setAttribute("lang", lang === "vi" ? "vi" : "en");
    document.documentElement.setAttribute("data-lang", lang);
    applyDom();
    return lang;
  }

  function toggle() {
    return setLang(lang === "vi" ? "en" : "vi");
  }

  function load() {
    try {
      const saved = localStorage.getItem("grok-build-lang");
      if (saved === "vi" || saved === "en") lang = saved;
    } catch {
      // ignore
    }
    document.documentElement.setAttribute("lang", lang === "vi" ? "vi" : "en");
    document.documentElement.setAttribute("data-lang", lang);
  }

  function applyDom(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (!key) return;
      const val = t(key);
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        if (el.hasAttribute("placeholder")) el.placeholder = val;
      } else {
        el.textContent = val;
      }
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (key) el.placeholder = t(key);
    });
    scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const key = el.getAttribute("data-i18n-title");
      if (key) el.title = t(key);
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const key = el.getAttribute("data-i18n-aria");
      if (key) el.setAttribute("aria-label", t(key));
    });
    const langBtn = document.getElementById("btnLang");
    if (langBtn) {
      langBtn.setAttribute("data-lang", lang);
      langBtn.title = `${t("switchLang")} (${lang.toUpperCase()})`;
      const badge = langBtn.querySelector(".lang-badge");
      if (badge) badge.textContent = lang.toUpperCase();
    }
  }

  global.GrokI18n = { t, getLang, setLang, toggle, load, applyDom, STR };
